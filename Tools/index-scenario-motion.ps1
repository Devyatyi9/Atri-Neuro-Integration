param(
    [string]$SceneRoot = 'D:\Games\ATRI-TestVersion\ks-scn-decompiled',
    [string]$OutputDirectory = "$PSScriptRoot\..\docs-local\research\scenario"
)

$ErrorActionPreference = 'Stop'

function Get-ActionSummary {
    param([object]$Value)

    $properties = [System.Collections.Generic.List[string]]::new()
    $durations = [System.Collections.Generic.List[string]]::new()
    foreach ($action in $Value.action) {
        if ($null -eq $action -or $action.Count -lt 2 -or $null -eq $action[0]) {
            continue
        }

        $properties.Add($action[0])
        if ($action[1] -is [System.Collections.IEnumerable] -and $action[1] -isnot [string]) {
            foreach ($keyframe in $action[1]) {
                if ($null -ne $keyframe.time) {
                    $durations.Add([string]$keyframe.time)
                }
            }
        }
    }

    return [pscustomobject]@{
        Properties = ($properties | Sort-Object -Unique) -join ', '
        DurationsMs = ($durations | Sort-Object -Unique) -join ', '
    }
}

$entries = [System.Collections.Generic.List[object]]::new()
Get-ChildItem -LiteralPath $SceneRoot -Recurse -Filter '*.ks.json' -File | ForEach-Object {
    $document = Get-Content -Raw -LiteralPath $_.FullName | ConvertFrom-Json -Depth 100
    $sceneName = $_.BaseName -replace '\.ks$', ''
    foreach ($scenarioScene in $document.scenes) {
        for ($lineIndex = 0; $lineIndex -lt $scenarioScene.lines.Count; $lineIndex++) {
            $line = $scenarioScene.lines[$lineIndex]
            if ($line.Count -lt 3 -or $line[0] -ne 'envupdate') {
                continue
            }

            $objects = $line[2]
            $motion = [System.Collections.Generic.List[object]]::new()
            foreach ($object in $objects) {
                if ($null -eq $object -or $null -eq $object.action) {
                    continue
                }
                $summary = Get-ActionSummary $object
                if ($summary.DurationsMs) {
                    $motion.Add([pscustomobject]@{
                        Name = $object.name
                        Class = $object.class
                        Properties = $summary.Properties
                        DurationsMs = $summary.DurationsMs
                    })
                }
            }

            $transIndex = [array]::IndexOf($line, 'trans')
            $transition = if ($transIndex -ge 0 -and $line.Count -gt $transIndex + 1) { $line[$transIndex + 1] } else { $null }
            if ($motion.Count -eq 0 -and $null -eq $transition) {
                continue
            }

            $entries.Add([pscustomobject]@{
                Scene = $sceneName
                Label = $scenarioScene.label
                LineIndex = $lineIndex
                MotionObjects = ($motion | ForEach-Object { "$($_.Name) [$($_.Class)]: $($_.Properties) ($($_.DurationsMs) ms)" }) -join ' | '
                TransitionMethod = $transition.method
                TransitionTimeMs = $transition.time
            })
        }
    }
}

New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null
$entries | Sort-Object Scene, Label, LineIndex |
    Export-Csv -NoTypeInformation -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'psb-motion-transition-index.csv')

$motionCount = @($entries | Where-Object MotionObjects).Count
$transitionCount = @($entries | Where-Object TransitionMethod).Count
$markdown = @(
    '# PSB Motion And Transition Index',
    '',
    "Generated by `Tools/index-scenario-motion.ps1` from `$SceneRoot`.",
    '',
    "- `envupdate` entries with motion and/or transition data: $($entries.Count)",
    "- Entries with timed object motion: $motionCount",
    "- Entries with transitions: $transitionCount",
    '',
    '## Format',
    '',
    'PSB camera-like movement is represented by timed `MoveAction` keyframes on `envupdate` stage/event objects, typically through `xpos`, `ypos`, `zoomx`, and `zoomy`. Visual scene transitions are sibling `trans` objects with `method` and `time`.',
    '',
    'The CSV uses the zero-based index in `scenes[].lines[]`, not a KAG source line. Use the player source-line API only after separately resolving an appropriate checkpoint.'
)
$markdown | Set-Content -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'psb-motion-transition-index.md')
