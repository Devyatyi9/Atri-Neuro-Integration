param(
    [string]$SceneRoot = 'D:\Games\ATRI-TestVersion\ks-scn-decompiled',
    [string]$OutputDirectory = "$PSScriptRoot\..\docs-local\research\scenario"
)

$ErrorActionPreference = 'Stop'

$quakes = [System.Collections.Generic.List[object]]::new()
$overlays = [System.Collections.Generic.List[object]]::new()
Get-ChildItem -LiteralPath $SceneRoot -Recurse -Filter '*.ks.json' -File | ForEach-Object {
    $document = Get-Content -Raw -LiteralPath $_.FullName | ConvertFrom-Json -Depth 100
    $sceneName = $_.BaseName -replace '\.ks$', ''
    foreach ($scenarioScene in $document.scenes) {
        for ($lineIndex = 0; $lineIndex -lt $scenarioScene.lines.Count; $lineIndex++) {
            $line = $scenarioScene.lines[$lineIndex]
            if ($line -isnot [System.Collections.IEnumerable] -or $line -is [string] -or $line.Count -lt 1) {
                continue
            }

            if ($line[0] -eq 'quake') {
                $parameters = [ordered]@{}
                for ($parameterIndex = 1; $parameterIndex + 1 -lt $line.Count; $parameterIndex += 2) {
                    $parameters[$line[$parameterIndex]] = $line[$parameterIndex + 1]
                }
                $quakes.Add([pscustomobject]@{
                    Scene = $sceneName
                    Label = $scenarioScene.label
                    LineIndex = $lineIndex
                    TimeMs = $parameters.time
                    HMax = $parameters.hmax
                    VMax = $parameters.vmax
                    Loop = $parameters.loop
                    Sync = $parameters.sync
                    NoWait = $parameters.nowait
                })
                continue
            }

            if ($line[0] -ne 'envupdate' -or $line.Count -lt 3) {
                continue
            }

            foreach ($object in $line[2]) {
                if ($null -eq $object -or ($object.class -ne 'event' -and $object.class -ne 'noevent')) {
                    continue
                }
                $imageFile = $object.redraw.imageFile.file
                if ($null -eq $imageFile -or $imageFile -eq '') {
                    continue
                }
                $overlays.Add([pscustomobject]@{
                    Scene = $sceneName
                    Label = $scenarioScene.label
                    LineIndex = $lineIndex
                    Name = $object.name
                    Class = $object.class
                    ImageFile = $imageFile
                    ShowMode = $object.showmode
                })
            }
        }
    }
}

New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null
$quakes | Sort-Object Scene, Label, LineIndex |
    Export-Csv -NoTypeInformation -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'psb-quake-index.csv')
$overlays | Sort-Object Scene, Label, LineIndex, Name |
    Export-Csv -NoTypeInformation -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'psb-overlay-index.csv')

$markdown = @(
    '# PSB Effect Index',
    '',
    "Generated by `Tools/index-scenario-effects.ps1` from `$SceneRoot`.",
    '',
    "- Quake commands: $($quakes.Count)",
    "- Event/noevent image overlays: $($overlays.Count)",
    '',
    '## Files',
    '',
    '- `psb-quake-index.csv`: direct PSB `quake` commands and their parameters.',
    '- `psb-overlay-index.csv`: `event` and `noevent` images created by `envupdate`; these are candidates for visual overlays, not a complete semantic effect catalog.'
)
$markdown | Set-Content -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'psb-effect-index.md')
