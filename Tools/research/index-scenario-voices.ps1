param(
    [string]$SceneRoot = 'D:\Games\ATRI-TestVersion\ks-scn-decompiled',
    [string]$OutputDirectory = "$PSScriptRoot\..\..\docs-local\research\audio"
)

$ErrorActionPreference = 'Stop'

function Get-LocalizedText {
    param(
        [object]$LocalizedText,
        [int]$LanguageIndex
    )

    if ($null -eq $LocalizedText -or $LocalizedText.Count -le $LanguageIndex) {
        return ''
    }

    $entry = $LocalizedText[$LanguageIndex]
    if ($null -eq $entry -or $entry.Count -lt 2 -or $null -eq $entry[1]) {
        return ''
    }

    return $entry[1] -join "`n"
}

$references = [System.Collections.Generic.List[object]]::new()
Get-ChildItem -LiteralPath $SceneRoot -Recurse -Filter '*.ks.json' -File | ForEach-Object {
    $document = Get-Content -Raw -LiteralPath $_.FullName | ConvertFrom-Json -Depth 100
    $sceneName = $_.BaseName -replace '\.ks$', ''
    foreach ($scenarioScene in $document.scenes) {
        $title = @($scenarioScene.title)
        for ($textIndex = 0; $textIndex -lt $scenarioScene.texts.Count; $textIndex++) {
            $textEntry = $scenarioScene.texts[$textIndex]
            $voices = $textEntry[3]
            if ($null -eq $voices) {
                continue
            }

            foreach ($voice in $voices) {
                if ($null -eq $voice.voice -or $voice.voice -eq '') {
                    continue
                }

                $references.Add([pscustomobject]@{
                    Scene = $sceneName
                    Label = $scenarioScene.label
                    TitleJapanese = $title[0]
                    TitleEnglish = $title[1]
                    TextIndex = $textIndex
                    Speaker = $textEntry[0]
                    VoiceSpeaker = $voice.name
                    VoiceSpeakerEnglish = $textEntry[2][1][0]
                    VoiceFile = $voice.voice
                    VoiceAsset = "$($voice.voice).opus"
                    Pan = $voice.pan
                    Type = $voice.type
                    TextJapanese = Get-LocalizedText $textEntry[2] 0
                    TextEnglish = Get-LocalizedText $textEntry[2] 1
                    TextChineseSimplified = Get-LocalizedText $textEntry[2] 2
                    TextChineseTraditional = Get-LocalizedText $textEntry[2] 3
                })
            }
        }
    }
}

New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null
$references | Sort-Object Scene, Label, TextIndex, VoiceFile |
    Export-Csv -NoTypeInformation -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'scenario-voice-occurrences.csv')

$usage = $references | Group-Object VoiceFile | ForEach-Object {
    $first = $_.Group[0]
    [pscustomobject]@{
        VoiceFile = $first.VoiceFile
        VoiceAsset = $first.VoiceAsset
        Occurrences = $_.Count
        Speakers = ($_.Group.VoiceSpeaker | Sort-Object -Unique) -join ', '
        Scenes = ($_.Group.Scene | Sort-Object -Unique) -join ', '
    }
}
$usage | Sort-Object VoiceFile |
    Export-Csv -NoTypeInformation -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'scenario-voice-usage.csv')

$characterMap = $references | Group-Object {
    if ($_.VoiceFile -match '^([^_]+)_') { $matches[1] } else { $_.VoiceFile }
} | ForEach-Object {
    $first = $_.Group[0]
    $allEnglishNames = @($_.Group.VoiceSpeakerEnglish | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Sort-Object -Unique)
    [pscustomobject]@{
        VoiceIdPrefix = $_.Name
        Character = ($_.Group.VoiceSpeaker | Sort-Object -Unique) -join ', '
        CharacterEnglish = $allEnglishNames -join ', '
        VoiceIds = $_.Count
        ExampleVoiceId = ($_.Group.VoiceFile | Sort-Object | Select-Object -First 1)
        Scenes = ($_.Group.Scene | Sort-Object -Unique) -join ', '
    }
}
$characterMap | Sort-Object VoiceIdPrefix |
    Export-Csv -NoTypeInformation -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'voice-id-character-map.csv')

$markdown = @(
    '# Scenario Voice Index',
    '',
    "Generated by `Tools/research/index-scenario-voices.ps1` from `$SceneRoot`.",
    '',
    "- Scene files: $(@($references.Scene | Sort-Object -Unique).Count)",
    "- Voice occurrences: $($references.Count)",
    "- Unique voice files: $($usage.Count)",
    '',
    '## Files',
    '',
    '- `voice-id-character-map.csv`: compact voice-ID prefix to character mapping, with an example ID and count.',
    '- `scenario-voice-occurrences.csv`: one row per voiced text entry with localized text and voice metadata.',
    '- `scenario-voice-usage.csv`: one row per voice file with speaker and scene summaries.',
    '',
    'Voice IDs are stored in PSB `scenes[].texts[][3][]` objects. The file stem is the engine storage name; `.opus` is the expected asset extension. `charvoice.csv` maps speakers to voice prefixes/configuration, but does not map individual lines.'
)
$markdown | Set-Content -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'scenario-voice-index.md')
