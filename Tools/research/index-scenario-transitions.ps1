param(
    [string]$SceneRoot = 'D:\Games\ATRI-TestVersion\ks-scn-decompiled',
    [string]$OutputDirectory = "$PSScriptRoot\..\..\docs-local\research\scenario"
)

$ErrorActionPreference = 'Stop'

function Join-TransitionValue {
    param([object]$Value)

    if ($null -eq $Value) {
        return ''
    }
    if ($Value -is [System.Collections.IEnumerable] -and $Value -isnot [string]) {
        return ($Value | ForEach-Object { [string]$_ }) -join ', '
    }
    return [string]$Value
}

$transitions = [System.Collections.Generic.List[object]]::new()
Get-ChildItem -LiteralPath $SceneRoot -Recurse -Filter '*.ks.json' -File | ForEach-Object {
    $document = Get-Content -Raw -LiteralPath $_.FullName | ConvertFrom-Json -Depth 100
    $sceneName = $_.BaseName -replace '\.ks$', ''
    foreach ($scenarioScene in $document.scenes) {
        $next = $scenarioScene.nexts
        $storage = Join-TransitionValue $next.storage
        $target = Join-TransitionValue $next.target
        $type = Join-TransitionValue $next.type
        $kind = if (-not $storage -and -not $target) {
            'No static target'
        } elseif ($storage -eq "$sceneName.ks" -and $target -eq '*end') {
            'Internal end'
        } elseif ($storage -eq 'start.ks' -and $target -eq '*gameend_title') {
            'System game end'
        } elseif ($storage -match ', ' -or $target -match ', ') {
            'Branch'
        } else {
            'Scene jump'
        }

        $transitions.Add([pscustomobject]@{
            Scene = $sceneName
            Label = $scenarioScene.label
            SourceLine = $scenarioScene.firstLine
            TransitionKind = $kind
            TargetStorage = $storage
            TargetLabel = $target
            TargetType = $type
        })
    }
}

New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null
$transitions | Sort-Object Scene, SourceLine |
    Export-Csv -NoTypeInformation -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'psb-transition-map.csv')

$markdown = @(
    '# PSB Transition Map',
    '',
    "Generated by `Tools/research/index-scenario-transitions.ps1` from `$SceneRoot`.",
    '',
    "- PSB scene nodes: $($transitions.Count)",
    "- Internal end transitions: $(@($transitions | Where-Object TransitionKind -eq 'Internal end').Count)",
    "- Scene jumps: $(@($transitions | Where-Object TransitionKind -eq 'Scene jump').Count)",
    "- Branches: $(@($transitions | Where-Object TransitionKind -eq 'Branch').Count)",
    "- System game endings: $(@($transitions | Where-Object TransitionKind -eq 'System game end').Count)",
    "- Nodes without a static target: $(@($transitions | Where-Object TransitionKind -eq 'No static target').Count)",
    '',
    '## Format',
    '',
    'PSB scenario progression is stored in `scenes[].nexts`, not as inline KAG `jump`/`call` tags. `SourceLine` is the PSB source-line checkpoint (`scenes[].firstLine`) suitable for the existing `KAGEnvPlayer.startScene(storage, line)` research route. Branch arrays remain comma-separated in the CSV in their original order; do not assume the first branch is selected.'
)
$markdown | Set-Content -Encoding utf8BOM -LiteralPath (Join-Path $OutputDirectory 'psb-transition-map.md')
